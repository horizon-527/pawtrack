const assert = require('assert');
let page;
require('../miniprogram/config').apiMode = 'prototype';
global.Page = definition => { page = definition; };
global.wx = {request: () => { throw new Error('unexpected network call'); }};
require('../miniprogram/pages/index/index');
page.data = {...page.data};
page.setData = value => Object.assign(page.data, value);
(async () => {
  page.active = true;
  await page.refresh();
  assert.equal(page.data.markers.length, 1);
  assert.equal(page.data.count, 40);
  assert(page.data.status.includes('模拟'));
  let requests = [];
  global.wx.request = options => requests.push(options);
  page.data.demo = false;
  const pending = page.refresh();
  assert.equal(requests.length, 2);
  page.revision = 1;
  page.data.demo = true;
  await page.refresh();
  requests[0].success({statusCode:200, data:null});
  requests[1].success({statusCode:200, data:[]});
  await pending;
  assert(page.data.status.includes('模拟'), 'outdated API responses must not overwrite demo');
  page.stop();
  assert.equal(page.active, false);
  console.log('Mini program rendering and stale-request checks passed');
})().catch(error => {console.error(error); process.exitCode = 1;});
